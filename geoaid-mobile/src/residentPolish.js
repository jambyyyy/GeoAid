// Merge by style key to preserve original Flexbox and screen-specific layout.
export function mergeResidentStyles(base, screen) {
  const updates = variants[screen] || {};
  const result = { ...base };
  Object.keys(updates).forEach((key) => {
    result[key] = { ...(base[key] || {}), ...updates[key] };
  });
  return result;
}
